#!/usr/bin/env python3
"""Pack the lite web console into a C header so it can be served straight from flash.

The page is one hand-written file. Gzipped it is a few KB, which lives in .flash.rodata and
costs no RAM at rest - so the console needs no SPIFFS image, no SD card and no partition of
its own, and it works when the filesystem does not.

The mock data layer between the /*MOCK*/ markers is for opening index.html directly in a
browser; it is stripped here so it never ships.

    python tools/gen_lite_assets.py
"""
import gzip
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
SRC = HERE.parent / "src" / "mesh" / "http" / "lite" / "index.html"
OUT = SRC.parent / "WebUIAssets.h"

html = SRC.read_bytes()
stripped = re.sub(rb"/\*MOCK\*/.*?/\*ENDMOCK\*/", b"", html, flags=re.S)
if stripped == html:
    print("warning: no /*MOCK*/.../*ENDMOCK*/ block found - mock data may be shipping",
          file=sys.stderr)

# mtime=0 so rebuilding an unchanged page produces an identical header (no spurious diffs)
blob = gzip.compress(stripped, compresslevel=9, mtime=0)

lines = []
for i in range(0, len(blob), 16):
    lines.append("    " + " ".join(f"0x{b:02x}," for b in blob[i:i + 16]))

OUT.write_text(
    "// Generated by tools/gen_lite_assets.py - do not edit.\n"
    "// Source: src/mesh/http/lite/index.html\n"
    f"// {len(html):,} B source -> {len(stripped):,} B shipped -> {len(blob):,} B gzipped\n"
    "#pragma once\n"
    "#include <stdint.h>\n\n"
    "static const uint8_t WEBUI_INDEX_HTML_GZ[] = {\n"
    + "\n".join(lines)
    + "\n};\n",
    encoding="utf-8",
)

print(f"{SRC.name}: {len(html):,} B -> stripped {len(stripped):,} B -> gzip {len(blob):,} B")
print(f"wrote {OUT}")
