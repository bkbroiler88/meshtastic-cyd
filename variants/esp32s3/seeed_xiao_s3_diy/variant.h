#define LED_POWER 48
#define LED_STATE_ON 1 // State when LED is lit

#define BUTTON_PIN 1 // DIY: user button on D0/GPIO1 (not a strapping pin on S3)
#define BUTTON_NEED_PULLUP

// No battery sense on this build. BATTERY_PIN must NOT be defined at all: Power.cpp gates
// the analog read with #ifdef BATTERY_PIN, which is true even for a value of -1, so
// "#define BATTERY_PIN -1" made it analogRead(-1) and report garbage (~6.2 V x the 2.0
// ADC_MULTIPLIER). No MAX17048 fuel gauge is present either (I2C scan finds only the OLED),
// so with these undefined the node correctly reports USB-powered instead of a bogus voltage.
// #define BATTERY_PIN 2  // <- set to a real GPIO + ADC_MULTIPLIER only if a divider is wired
#define ADC_CHANNEL ADC_CHANNEL_0
#define BATTERY_SENSE_RESOLUTION_BITS 12

/*Warning:
    https://www.seeedstudio.com/L76K-GNSS-Module-for-Seeed-Studio-XIAO-p-5864.html
    L76K Expansion Board can not directly used, L76K Reset Pin needs to override or physically remove it,
    otherwise it will conflict with the SPI pins
*/
#define GPS_L76K
#ifdef GPS_L76K
#define GPS_RX_PIN 44
#define GPS_TX_PIN -1 // RX-only: GPIO43 freed for LoRa NSS (Wio leg cut + rerouted)
#define HAS_GPS 1
#define GPS_THREAD_INTERVAL 50
#define PIN_SERIAL1_RX PIN_GPS_TX
#define PIN_SERIAL1_TX PIN_GPS_RX
// DIY: GPS standby removed - GPIO1 is the user button now. GPS UART stays on
// 43/44 and the companion app enables/disables GPS.
// #define PIN_GPS_STANDBY 1
#endif

// DIY: 0.96" SSD1306 I2C OLED on D4/D5 (SDA 5, SCL 6). The stock variant wrote
// USCREEN_SSD1306, which is a typo the firmware ignores, so the screen never came
// up. USE_SSD1306 is the macro that actually compiles the driver.
#define USE_SSD1306

// Piglet, the pet pig frame (PigPetModule). Set here rather than in platformio.ini: an ini edit
// changes the project checksum and PlatformIO then wipes every environment's build directory.
#define PIG_PET

#define I2C_SDA 5
#define I2C_SCL 6

// XIAO S3 LORA module
#define USE_SX1262

#define LORA_MISO 8
#define LORA_SCK 7
#define LORA_MOSI 9
#define LORA_CS 43 // NSS rerouted off GPIO5 (collided with OLED SDA) to the freed GPS-TX pad

#define LORA_RESET 3 // schematic: J1.3 (D2)
#define LORA_DIO1 2  // schematic: J1.2 (D1)

#define LORA_DIO2 RADIOLIB_NC // RF switch handled by SX1262 DIO2 internally (DIO2_AS_RF_SWITCH)

#ifdef USE_SX1262
#define SX126X_CS LORA_CS
#define SX126X_DIO1 LORA_DIO1
#define SX126X_BUSY 4 // schematic: J1.4 (D3)
#define SX126X_RESET LORA_RESET

//  DIO2 controlls an antenna switch and the TCXO voltage is controlled by DIO3
#define SX126X_DIO2_AS_RF_SWITCH
#define SX126X_RXEN RADIOLIB_NC // RF_SW1/GPIO6 left for OLED SCL; antenna switch via DIO2
#define SX126X_TXEN RADIOLIB_NC
#define SX126X_DIO3_TCXO_VOLTAGE 1.8
#endif
